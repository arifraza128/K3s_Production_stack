#!/usr/bin/env python3
"""
Phase 8 — Automated DR Drill Scorecard Generator (DATABASE.md §6 & DESIGN.md §3)
Reads all docs/evidence/dr-drill/*.json files and generates docs/evidence/dr-drill/scorecard.md
without hand-edited numbers.
"""
import glob
import json
import os
import pathlib

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
DR_DIR = REPO_ROOT / "docs" / "evidence" / "dr-drill"
SCORECARD_PATH = DR_DIR / "scorecard.md"


def main() -> None:
    json_files = sorted(glob.glob(str(DR_DIR / "*.json")))
    rows = []
    for jf in json_files:
        with open(jf, "r", encoding="utf-8") as f:
            data = json.load(f)
        fname = os.path.basename(jf)
        date = data.get("date", "unknown")
        scenario = data.get("scenario", "unknown")
        rto = f"{data.get('rto_seconds', 0)}s"
        rpo = f"{data.get('rpo_seconds', 0)}s"
        data_loss = data.get("data_loss", "none")
        result = data.get("result", "UNKNOWN")
        link = f"[`{fname}`]({fname})"
        if result == "FAIL":
            link += " · [`postmortem.md`](postmortem.md)"
        rows.append(f"| `{date}` | `{scenario}` | `{rto}` | `{rpo}` | `{data_loss}` | **{result}** | {link} |")

    content = [
        "# Phase 8 Evidence — Disaster Recovery (DR) Drill Scorecard",
        "",
        "> Automatically generated by [`scripts/generate-scorecard.py`](../../../scripts/generate-scorecard.py) from `docs/evidence/dr-drill/<date>-<scenario>.json` per [`DATABASE.md`](../../../DATABASE.md) §6 and [`DESIGN.md`](../../../DESIGN.md) §3.",
        "",
        "| Date | Scenario | RTO | RPO | Data loss | Result | Link |",
        "| :--- | :--- | :--- | :--- | :--- | :--- | :--- |",
    ]
    if rows:
        content.extend(rows)
    else:
        content.append("| `not yet measured` | `not yet measured` | `not yet measured` | `not yet measured` | `not yet measured` | `not yet measured` | Pending JSON |")

    content.append("")
    SCORECARD_PATH.write_text("\n".join(content), encoding="utf-8")
    print(f"==> Generated scorecard with {len(rows)} drill row(s): {SCORECARD_PATH}")


if __name__ == "__main__":
    main()
